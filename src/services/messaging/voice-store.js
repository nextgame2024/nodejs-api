import { randomUUID } from "node:crypto";
import {
  schema as s,
  canDispatch,
  currentRelease,
  capabilityAllowed,
} from "./reply-store.js";
import { channelProfiles } from "./channel-profiles.js";
export const voiceEnabled = (p) =>
  process.env.WHATSAPP_VOICE_ENABLED === "true" &&
  p?.voiceEnabled === true &&
  /^[a-f0-9]{64}$/i.test(process.env[p?.mediaKeyEnv] ?? "");
export async function voiceInstalled(db) {
  return !!(
    await db.query(
      "SELECT to_regclass('sophia_runtime.assistant_voice_jobs') IS NOT NULL AS ready",
    )
  ).rows[0].ready;
}
export async function enqueueVoiceInbound(db, profile, leadId, eventId, isNew) {
  if (
    !voiceEnabled(profile) ||
    !profile.transcriptionAdapter ||
    !(await voiceInstalled(db))
  )
    return false;
  const row = (
    await db.query(
      `SELECT b.*,c.conversation_id,c.ownership_version,c.ownership FROM ${s}.assistant_reply_bindings b JOIN ${s}.assistant_channels h USING(customer_id,channel_id) JOIN ${s}.assistant_lead_conversations c ON c.customer_id=h.customer_id AND c.lead_id=$3 WHERE b.customer_id=$1 AND h.profile_id=$2`,
      [profile.customerId, profile.id, leadId],
    )
  ).rows[0];
  if (!row) return false;
  if (
    isNew &&
    row.mode === "automatic" &&
    process.env.WHATSAPP_AUTOMATION_ENABLED === "true" &&
    canDispatch(profile)
  ) {
    const c = (
      await db.query(
        `UPDATE ${s}.assistant_lead_conversations SET ownership='bot',ownership_version=ownership_version+1 WHERE customer_id=$1 AND lead_id=$2 AND ownership='human_requested' RETURNING ownership_version`,
        [profile.customerId, leadId],
      )
    ).rows[0];
    if (c) row.ownership_version = c.ownership_version;
  }
  await db.query(
    `INSERT INTO ${s}.assistant_voice_jobs(customer_id,channel_id,lead_id,conversation_id,kind,source_event_id,ownership_version,agent_release_id,binding_revision) VALUES($1,$2,$3,$4,'transcribe',$5,$6,$7,$8) ON CONFLICT DO NOTHING`,
    [
      profile.customerId,
      row.channel_id,
      leadId,
      row.conversation_id,
      eventId,
      row.ownership_version,
      row.agent_release_id,
      row.revision,
    ],
  );
  return true;
}
export async function queueVoicePair(db, tenant, messageId) {
  if (process.env.WHATSAPP_VOICE_ENABLED !== "true") return;
  const m = (
    await db.query(
      `SELECT o.*,h.profile_id,l.language FROM ${s}.assistant_message_outbox o JOIN ${s}.assistant_channels h USING(customer_id,channel_id) JOIN ${s}.assistant_leads l ON l.customer_id=o.customer_id AND l.lead_id=o.lead_id WHERE o.customer_id=$1 AND o.message_id=$2`,
      [tenant, messageId],
    )
  ).rows[0];
  const profile = channelProfiles().find(
    (p) => p.customerId === tenant && p.id === m?.profile_id,
  );
  if (!voiceEnabled(profile) || !(await voiceInstalled(db))) return;
  const binding = (
    await db.query(
      `SELECT * FROM ${s}.assistant_reply_bindings WHERE customer_id=$1 AND channel_id=$2`,
      [tenant, m.channel_id],
    )
  ).rows[0];
  if (!binding) return;
  const id = randomUUID();
  const inserted = await db.query(
    `INSERT INTO ${s}.assistant_message_outbox(message_id,customer_id,channel_id,lead_id,conversation_id,ownership_version,actor_identity,body,request_key,request_hash,job_id,format,parent_message_id,state) VALUES($1,$2,$3,$4,$5,$6,$7,$8,$1,$9,$10,'audio',$11,'preparing') ON CONFLICT DO NOTHING RETURNING message_id`,
    [
      id,
      tenant,
      m.channel_id,
      m.lead_id,
      m.conversation_id,
      m.ownership_version,
      m.actor_identity,
      m.body,
      m.request_hash,
      m.job_id,
      m.message_id,
    ],
  );
  if (!inserted.rowCount) return;
  await db.query(
    `INSERT INTO ${s}.assistant_voice_jobs(customer_id,channel_id,lead_id,conversation_id,kind,message_id,ownership_version,agent_release_id,binding_revision) VALUES($1,$2,$3,$4,'synthesize',$5,$6,$7,$8)`,
    [
      tenant,
      m.channel_id,
      m.lead_id,
      m.conversation_id,
      id,
      m.ownership_version,
      binding.agent_release_id,
      binding.revision,
    ],
  );
  const disclosure =
    {
      es: "Respuesta de voz generada por IA.",
      pt: "Resposta de voz gerada por IA.",
      en: "Voice reply generated by AI.",
    }[m.language] ?? "Voice reply generated by AI.";
  await db.query(
    `UPDATE ${s}.assistant_message_outbox SET body=body||E'\n\n'||$3 WHERE customer_id=$1 AND message_id=$2`,
    [tenant, m.message_id, disclosure],
  );
}
export async function approveSpeech(db, tenant, job, profile) {
  const release = await currentRelease(db, tenant, job.agent_release_id);
  return capabilityAllowed(
    db,
    tenant,
    release,
    job.kind === "transcribe" ? "speech-input" : "speech-output",
    job.kind === "transcribe"
      ? profile.transcriptionAdapter
      : profile.synthesisAdapter,
    job.kind === "transcribe"
      ? profile.transcriptionCredentialRef
      : profile.synthesisCredentialRef,
  );
}

export async function voiceState(db, tenant, access, leadId) {
  if (!(await voiceInstalled(db))) return [];
  const rows = (
    await db.query(
      `SELECT j.voice_job_id AS id,j.kind,j.state,j.failure_code AS "failureCode",j.created_at AS "createdAt",
 (j.kind='synthesize' AND o.state='failed' AND o.safe_code IN ('voice_generation_failed','voice_preparation_failed') AND j.attempts<2 AND c.ownership_version=j.ownership_version AND l.stage<>'closed' AND NOT t.opted_out AND t.last_inbound_at>now()-interval '24 hours' AND ((c.ownership='human' AND c.human_owner_identity=$3) OR(c.ownership='bot' AND $4::boolean))) AS "canRetry"
 FROM ${s}.assistant_voice_jobs j JOIN ${s}.assistant_lead_conversations c USING(customer_id,conversation_id) JOIN ${s}.assistant_leads l ON l.customer_id=j.customer_id AND l.lead_id=j.lead_id JOIN ${s}.assistant_channel_contacts t ON t.customer_id=j.customer_id AND t.lead_id=j.lead_id LEFT JOIN ${s}.assistant_message_outbox o ON o.customer_id=j.customer_id AND o.message_id=j.message_id WHERE j.customer_id=$1 AND j.lead_id=$2 ORDER BY j.created_at DESC LIMIT 10`,
      [tenant, leadId, access.actor, access.canManageLeads],
    )
  ).rows;
  return rows;
}
